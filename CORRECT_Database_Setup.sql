-- Step 7: Create/verify users table
CREATE TABLE IF NOT EXISTS public.users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "firstName" text NOT NULL,
  email text NULL,
  "lastName" text NULL,
  "middleName" text NULL,
  suffix text NULL,
  "contactNumber" text NULL,
  "userTypeId" text NULL UNIQUE,  -- Supabase Auth UUID
  "isActive" boolean NULL DEFAULT true,
  "profilePictureUrl" text NULL,
  address text NULL,
"emergencyContact" text NULL,
  CONSTRAINT users_userTypeId_key UNIQUE ("userTypeId")
);

-- Step 8: DROP old user_roles table and recreate with correct schema
DROP TABLE IF EXISTS public.user_roles CASCADE;

CREATE TABLE public.user_roles (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  "userId" text NOT NULL UNIQUE,  -- References users.userTypeId
  "roleId" bigint NOT NULL,  -- CHANGED: Now references roles.id (numeric)
  CONSTRAINT user_roles_userId_key UNIQUE ("userId"),
  CONSTRAINT user_roles_roleid_fkey FOREIGN KEY ("roleId") REFERENCES roles (id),
  CONSTRAINT user_roles_userId_fkey FOREIGN KEY ("userId") REFERENCES users ("userTypeId")
);

-- Step 9: Create/verify studentProfile table
CREATE TABLE IF NOT EXISTS public."studentProfile" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "studentId" text NULL,  -- References users.userTypeId
  "yearLevel" integer NULL,
  "programId" bigint NULL,-- FK to programs table
  "departmentId" bigint NULL,  -- FK to departments table
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  CONSTRAINT studentProfile_studentId_fkey FOREIGN KEY ("studentId") REFERENCES users ("userTypeId"),
  CONSTRAINT studentProfile_programId_fkey FOREIGN KEY ("programId") REFERENCES programs (id),
  CONSTRAINT studentProfile_departmentId_fkey FOREIGN KEY ("departmentId") REFERENCES departments (id)
);

-- Step 10: Create/verify teacherProfile table
CREATE TABLE IF NOT EXISTS public."teacherProfile" (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "departmentId" bigint NULL,  -- FK to departments table
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  "teacherId" text NULL,-- References users.userTypeId
  CONSTRAINT teacherProfile_teacherId_fkey FOREIGN KEY ("teacherId") REFERENCES users ("userTypeId"),
  CONSTRAINT teacherProfile_departmentId_fkey FOREIGN KEY ("departmentId") REFERENCES departments (id)
);

