-- Step 1: Create departments table (if not exists)
CREATE TABLE IF NOT EXISTS public.departments (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "departmentName" text NOT NULL,
  "departmentCode" text NULL,
  created_at timestamp with time zone NOT NULL DEFAULT now()
);

-- Step 2: Create programs table (if not exists)
CREATE TABLE IF NOT EXISTS public.programs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  created_at timestamp with time zone NOT NULL DEFAULT now(),
  "programName" text NULL,
  "programCode" text NULL,
  "departmentId" bigint NULL,
  CONSTRAINT programs_departmentId_fkey FOREIGN KEY ("departmentId") REFERENCES departments (id)
);

